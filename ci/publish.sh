#!/usr/bin/env bash
# Publish one agent run to its pull request. This is the only step with write
# access, and it never executes pull request code and never calls the LLM: it applies
# a patch verify has already checked, and posts text rendered from JSON.
#
#   ci/publish.sh <agent-out> <verify-out>
#
# Env: GH_TOKEN, GITHUB_REPOSITORY, PR_NUMBER, PR_HEAD_SHA (the head the agent saw),
#      PR_HEAD_REF, RUN_URL
#
# 1. push the verified tests to the PR branch, only if the branch has not moved
# 2. commit status `tf-test-agent` on the resulting head
# 3. one summary comment, updated in place on later runs
# 4. inline review comments for findings on changed lines, each posted once
# 5. dispatch terraform-checks for the new commit (GITHUB_TOKEN pushes trigger nothing)

set -euo pipefail

agent="${1:?usage: publish.sh <agent-out> <verify-out>}"
verify="${2:?}"
mkdir -p "$agent" "$verify"
ci_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
repo="${GITHUB_REPOSITORY:?}" pr="${PR_NUMBER:?}" head_sha="${PR_HEAD_SHA:?}" head_ref="${PR_HEAD_REF:?}"
run_url="${RUN_URL:-}"
work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT

log() { printf '%s\n' "$*" >&2; }
verified="$verify/verified.json"
[[ -s "$verified" ]] || echo '{"ok":false,"push":false,"patch":{"problems":["verify did not run"]}}' >"$verified"

current_head="$(gh api "repos/$repo/pulls/$pr" --jq .head.sha)"
stale=false
if [[ "$current_head" != "$head_sha" ]]; then
  stale=true
  log "PR head moved from $head_sha to $current_head during the run; not pushing"
fi

# --- 1. Push ---------------------------------------------------------------------------
pushed="-"
if ! $stale && jq -e .push "$verified" >/dev/null; then
  git clone -q --depth 1 --branch "$head_ref" --no-tags "https://github.com/$repo.git" "$work/pr"
  cd "$work/pr"
  if [[ "$(git rev-parse HEAD)" == "$head_sha" ]] && git apply --check "$agent/tests.patch"; then
    git apply "$agent/tests.patch"
    mapfile -t files < <(jq -r '.patch.files[]' "$verified")
    git add -- "${files[@]}"
    git -c user.name="github-actions[bot]" \
        -c user.email="41898282+github-actions[bot]@users.noreply.github.com" \
        commit -q -m "test: add or update terraform tests (tf-test-agent)" \
        -m "Verified in $run_url" -m "Generated by the tf-test-agent workflow; review like any other commit."
    auth="$(printf 'x-access-token:%s' "$GH_TOKEN" | base64 -w0)"
    if git -c "http.https://github.com/.extraheader=AUTHORIZATION: basic $auth" \
         push -q origin "HEAD:refs/heads/$head_ref"; then
      pushed="$(git rev-parse HEAD)"
      log "pushed $pushed"
    else
      log "push rejected (branch moved?); tests not pushed"
    fi
  else
    log "branch is not at the verified head; not pushing"
  fi
  cd - >/dev/null
fi
final_sha="$head_sha"
[[ "$pushed" != "-" ]] && final_sha="$pushed"

# --- 2. Comment and review content -----------------------------------------------------
gh api --paginate "repos/$repo/pulls/$pr/files" | python3 -I "$ci_dir/diff_lines.py" >"$work/lines.json"
python3 -I "$ci_dir/render_comment.py" "$agent" "$verify" "$pushed" "$run_url" "$work/lines.json"

# --- 3. Status ---------------------------------------------------------------------------
if [[ ! -s "$agent/report.json" ]]; then
  state=error description="agent did not produce a report"
elif jq -e '.ok' "$verified" >/dev/null || ! jq -e '.patch.files | length > 0' "$verified" >/dev/null; then
  if jq -e '.report.valid' "$verified" >/dev/null; then
    state=success
    description="$(jq -r '"tests verified; \(.findings | length) finding(s), \([.findings[] | select(.severity == "high")] | length) high"' "$agent/report.json")"
  else
    state=failure description="agent report failed validation"
  fi
else
  state=failure description="generated tests failed verification; not pushed"
fi
gh api -X POST "repos/$repo/statuses/$final_sha" -f state="$state" -f context="tf-test-agent" \
  -f description="${description:0:139}" -f target_url="$run_url" >/dev/null

# --- 4. Summary comment, updated in place ------------------------------------------
marker='<!-- tf-test-agent:summary -->'
comment_id="$(gh api --paginate "repos/$repo/issues/$pr/comments" \
  --jq ".[] | select(.user.login == \"github-actions[bot]\" and (.body | contains(\"$marker\"))) | .id" | head -n1)"
jq -n --rawfile body "$verify/comment.md" '{body: $body}' >"$work/comment.json"
if [[ -n "$comment_id" ]]; then
  gh api -X PATCH "repos/$repo/issues/comments/$comment_id" --input "$work/comment.json" >/dev/null
else
  gh api -X POST "repos/$repo/issues/$pr/comments" --input "$work/comment.json" >/dev/null
fi

# --- 5. Inline findings, each once across runs ----------------------------------------
gh api --paginate "repos/$repo/pulls/$pr/comments" --jq '.[].body' |
  grep -oE 'tf-test-agent:finding:[0-9a-f]+' | sed 's/.*://' | sort -u >"$work/posted.txt" || true
jq --rawfile posted "$work/posted.txt" --arg sha "$final_sha" '
  ($posted | split("\n")) as $seen
  | [.[] | select(.key as $k | $seen | index($k) | not) | {path, line, side, body}] as $new
  | if ($new | length) == 0 then empty
    else {commit_id: $sha, event: "COMMENT", body: "", comments: $new} end
' "$verify/review.json" >"$work/review.json"
if [[ -s "$work/review.json" ]]; then
  gh api -X POST "repos/$repo/pulls/$pr/reviews" --input "$work/review.json" >/dev/null ||
    log "warning: inline review comments rejected; findings are in the summary comment"
fi

# --- 6. Checks for the commit we pushed ------------------------------------------------
if [[ "$pushed" != "-" ]]; then
  gh api -X POST "repos/$repo/actions/workflows/checks.yml/dispatches" -f ref="$head_ref" >/dev/null ||
    log "warning: could not dispatch terraform-checks for $pushed"
fi
log "published: status=$state pushed=$pushed"
